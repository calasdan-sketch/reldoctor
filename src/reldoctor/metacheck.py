"""Metadata rules PyPI applies on upload that need data tables: classifiers,
SPDX license expressions, author emails, Requires-Python and README links.

Tables live in `reldoctor/data/` (regenerated by tools/refresh_data.py) and are
snapshots; each is dated in its first line so a stale table is easy to spot.
Functions return (code, message) pairs; doctor.py turns them into Findings.
"""
from __future__ import annotations

import email.message
import email.utils
import os
import re
from functools import lru_cache
from typing import Dict, FrozenSet, List, Optional, Tuple

from . import pyspec

Pair = Tuple[str, str]
_DATA = os.path.join(os.path.dirname(__file__), "data")

CHECKS_EXTRA: Dict[str, Tuple[str, str]] = {
    "invalid_classifier": ("error", "a Classifier is not in the trove list; PyPI rejects it"),
    "deprecated_classifier": ("error", "a Classifier is deprecated; PyPI rejects new uploads that use it"),
    "invalid_license_expression": ("error", "License-Expression is not a valid SPDX expression; PyPI rejects it"),
    "license_classifier_mismatch": ("warn", "License classifier names a different license than License-Expression"),
    "bad_requires_python": ("error", "Requires-Python is not a valid version specifier; PyPI rejects it"),
    "python_classifier_conflict": ("warn", "a 'Programming Language :: Python :: X.Y' classifier is excluded by Requires-Python"),
    "invalid_author_email": ("error", "Author-email/Maintainer-email is not a valid address; PyPI rejects it"),
    "invalid_dynamic_field": ("error", "Dynamic names a field PyPI does not allow to be dynamic"),
    "bad_url_field": ("error", "Home-page or Download-URL is not a valid URI; PyPI rejects it"),
    "undeclared_extra": ("warn", "Requires-Dist uses an extra that no Provides-Extra declares"),
    "license_expression_old_metadata": ("error", "License-Expression needs Metadata-Version 2.4+; twine and packaging reject it"),
    "field_newer_than_metadata_version": ("warn", "a field was introduced after the declared Metadata-Version (strict packaging validation rejects it)"),
    "readme_relative_links": ("warn", "the long description links to relative paths; they break on PyPI"),
}


# --- tables ----------------------------------------------------------------

@lru_cache(maxsize=1)
def _trove() -> Tuple[FrozenSet[str], Dict[str, List[str]], str]:
    valid, dep, header = set(), {}, ""
    with open(os.path.join(_DATA, "trove_classifiers.txt"), encoding="utf-8") as fh:
        for i, line in enumerate(fh):
            line = line.rstrip("\n")
            if i == 0:
                m = re.match(r"# trove-classifiers (\S+)", line)
                header = f"trove-classifiers {m.group(1)}" if m else "bundled trove list"
            elif line.startswith("! "):
                old, _, new = line[2:].partition(" => ")
                dep[old] = [x.strip() for x in new.split(" | ") if x.strip()]
            elif line and not line.startswith("#"):
                valid.add(line)
    return frozenset(valid), dep, header


@lru_cache(maxsize=1)
def _spdx() -> Tuple[Dict[str, str], Dict[str, str]]:
    lic, exc = {}, {}
    with open(os.path.join(_DATA, "spdx_licenses.txt"), encoding="utf-8") as fh:
        for line in fh:
            if line.startswith("L "):
                lic[line[2:].strip().lower()] = line[2:].strip()
            elif line.startswith("E "):
                exc[line[2:].strip().lower()] = line[2:].strip()
    return lic, exc


def table_versions() -> Dict[str, str]:
    return {"trove": _trove()[2]}


# --- classifiers -----------------------------------------------------------

def check_classifiers(meta: email.message.Message) -> List[Pair]:
    valid, deprecated, header = _trove()
    out: List[Pair] = []
    bad, dep = [], []
    for c in dict.fromkeys(x.strip() for x in meta.get_all("Classifier", [])):
        if c in deprecated:
            dep.append(c)
        elif c not in valid:
            bad.append(c)
    for c in bad:
        out.append(("invalid_classifier",
                    f"classifier {c!r} is not a valid trove classifier (checked against {header}); "
                    "PyPI rejects the upload. Fix the spelling or remove it"))
    for c in dep:
        repl = deprecated[c]
        hint = f"use {' or '.join(map(repr, repl))} instead" if repl else "remove it"
        out.append(("deprecated_classifier",
                    f"classifier {c!r} is deprecated; PyPI rejects new uploads that use it: {hint}"))
    return out


_LICENSE_CLASSIFIER_TO_SPDX = {
    "License :: OSI Approved :: MIT License": {"MIT", "MIT-0"},
    "License :: OSI Approved :: Apache Software License": {"APACHE-2.0", "APACHE-1.1", "APACHE-1.0"},
    "License :: OSI Approved :: BSD License": {"BSD-3-CLAUSE", "BSD-2-CLAUSE", "BSD-3-CLAUSE-CLEAR", "0BSD", "BSD-4-CLAUSE"},
    "License :: OSI Approved :: ISC License (ISCL)": {"ISC"},
    "License :: OSI Approved :: Mozilla Public License 2.0 (MPL 2.0)": {"MPL-2.0"},
    "License :: OSI Approved :: GNU General Public License v3 (GPLv3)": {"GPL-3.0-ONLY", "GPL-3.0-OR-LATER", "GPL-3.0"},
    "License :: OSI Approved :: GNU General Public License v2 (GPLv2)": {"GPL-2.0-ONLY", "GPL-2.0-OR-LATER", "GPL-2.0"},
    "License :: OSI Approved :: GNU Affero General Public License v3": {"AGPL-3.0-ONLY", "AGPL-3.0-OR-LATER", "AGPL-3.0"},
    "License :: OSI Approved :: The Unlicense (Unlicense)": {"UNLICENSE"},
}


def check_license(meta: email.message.Message) -> List[Pair]:
    expr = (meta.get("License-Expression") or "").strip()
    out: List[Pair] = []
    if not expr:
        return out
    problem = spdx_problem(expr)
    if problem:
        out.append(("invalid_license_expression",
                    f"License-Expression {expr!r} is not a valid SPDX expression: {problem}. "
                    "Use SPDX ids such as 'MIT', 'Apache-2.0 OR MIT', 'GPL-3.0-or-later'"))
        return out
    ids = {t.upper().rstrip("+") for t in re.findall(r"[A-Za-z0-9.+-]+", expr)}
    for c in meta.get_all("Classifier", []):
        want = _LICENSE_CLASSIFIER_TO_SPDX.get(c.strip())
        if want and not (want & ids):
            out.append(("license_classifier_mismatch",
                        f"classifier {c.strip()!r} does not match License-Expression {expr!r}"))
    return out


_TOKEN = re.compile(r"\(|\)|[A-Za-z0-9.+-]+(?::[A-Za-z0-9.-]+)?")


def spdx_problem(expr: str) -> Optional[str]:
    """None when `expr` is a valid SPDX license expression (PEP 639), else why not."""
    lic, exc = _spdx()
    if len(expr) > 1024:
        return "too long"
    pos, tokens = 0, []
    expr = expr.strip()
    while pos < len(expr):
        if expr[pos].isspace():
            pos += 1
            continue
        m = _TOKEN.match(expr, pos)
        if not m:
            return f"unexpected character {expr[pos]!r}"
        tokens.append(m.group())
        pos = m.end()
    if not tokens:
        return "empty"
    i = 0

    def peek() -> Optional[str]:
        return tokens[i] if i < len(tokens) else None

    def simple(depth: int) -> Optional[str]:
        nonlocal i
        t = peek()
        if t is None:
            return "expression ends where a license id was expected"
        if t == "(":
            i += 1
            r = expression(depth + 1)
            if r:
                return r
            if peek() != ")":
                return "missing ')'"
            i += 1
            return None
        if t in (")",) or t.upper() in ("AND", "OR", "WITH"):
            return f"unexpected {t!r}"
        i += 1
        if t.upper().startswith("LICENSEREF-"):
            return None if re.fullmatch(r"(?i)LicenseRef-[A-Za-z0-9.-]+", t) else f"bad LicenseRef {t!r}"
        base = t[:-1] if t.endswith("+") else t
        if base.lower() not in lic:
            return f"unknown license id {t!r} (see https://spdx.org/licenses/)"
        if peek() is not None and peek().upper() == "WITH":
            i += 1
            e = peek()
            if e is None or e.lower() not in exc:
                return f"unknown license exception {e!r}"
            i += 1
        return None

    def expression(depth: int) -> Optional[str]:
        nonlocal i
        if depth > 32:
            return "nested too deeply"
        r = simple(depth)
        if r:
            return r
        while peek() is not None and peek().upper() in ("AND", "OR"):
            i += 1
            r = simple(depth)
            if r:
                return r
        return None

    r = expression(0)
    if r:
        return r
    if i != len(tokens):
        return f"unexpected {tokens[i]!r}"
    return None


# --- Requires-Python, extras, emails, dynamic -------------------------------

def check_requires_python(meta: email.message.Message) -> List[Pair]:
    spec = (meta.get("Requires-Python") or "").strip()
    out: List[Pair] = []
    if not spec:
        return out
    if pyspec.split_clauses(spec) is None:
        return [("bad_requires_python", f"Requires-Python {spec!r} is not a valid specifier "
                                        "(expected e.g. '>=3.9' or '>=3.9,<4')")]
    conflicts = []
    for c in meta.get_all("Classifier", []):
        m = re.fullmatch(r"Programming Language :: Python :: (\d)\.(\d+)", c.strip())
        if m and pyspec.allows_minor(spec, int(m.group(1)), int(m.group(2))) is False:
            conflicts.append(f"{m.group(1)}.{m.group(2)}")
    if conflicts:
        out.append(("python_classifier_conflict",
                    f"Requires-Python {spec!r} excludes Python {', '.join(conflicts)}, "
                    "which classifiers still advertise"))
    return out


_EXTRA_MARK = re.compile(r"""extra\s*==\s*["']([^"']+)["']""")


def _norm_extra(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def check_extras(meta: email.message.Message) -> List[Pair]:
    declared = {_norm_extra(e) for e in meta.get_all("Provides-Extra", [])}
    used = set()
    for req in meta.get_all("Requires-Dist", []):
        if ";" in req:
            used |= {_norm_extra(x) for x in _EXTRA_MARK.findall(req.split(";", 1)[1])}
    missing = sorted(used - declared)
    if not missing:
        return []
    return [("undeclared_extra", f"Requires-Dist uses extra(s) {missing} that no Provides-Extra declares; "
                                 "installers may ignore those dependencies")]


_BAD_TLDS = {"arpa", "invalid", "local", "localhost", "onion", "test"}
_ADDR = re.compile(r"^[^@\s<>()\[\]\\,;:\"]+@([A-Za-z0-9-]+(?:\.[A-Za-z0-9-]+)+)$")


def check_emails(meta: email.message.Message) -> List[Pair]:
    out: List[Pair] = []
    for field in ("Author-email", "Maintainer-email"):
        value = meta.get(field)
        if not value:
            continue
        for _, addr in email.utils.getaddresses([str(value)]):
            if not addr:
                continue
            m = _ADDR.match(addr)
            if not m or m.group(1).rsplit(".", 1)[-1].lower() in _BAD_TLDS:
                out.append(("invalid_author_email",
                            f"{field} address {addr!r} is not valid (PyPI runs email-validator on it; "
                            "special-use names such as .local/.test/.invalid are refused)"))
    return out


DYNAMIC_ALLOWED = {x.lower() for x in (
    "Platform Supported-Platform Summary Description Description-Content-Type Keywords Home-Page "
    "Download-Url Author Author-Email Maintainer Maintainer-Email License License-Expression "
    "License-File Classifier Requires-Dist Requires-Python Requires-External Project-Url "
    "Provides-Extra Provides-Dist Obsoletes-Dist Requires Provides Obsoletes Import-Name "
    "Import-Namespace").split()}

# Metadata version in which each field first appeared (core metadata spec).
# License-File is deliberately absent: setuptools/wheel emitted it under 2.1 for
# years and PyPI/twine accept that (requests, click, lxml, pillow all do).
FIELD_SINCE = {
    "requires-dist": (1, 2), "requires-python": (1, 2), "project-url": (1, 2),
    "provides-dist": (1, 2), "obsoletes-dist": (1, 2), "requires-external": (1, 2),
    "dynamic": (2, 2), "provides-extra": (2, 1), "description-content-type": (2, 1),
    "license-expression": (2, 4),
    "import-name": (2, 5), "import-namespace": (2, 5),
}


def check_dynamic_and_versions(meta: email.message.Message, md_version: Tuple[int, int]) -> List[Pair]:
    out: List[Pair] = []
    for d in meta.get_all("Dynamic", []):
        if d.strip().lower() not in DYNAMIC_ALLOWED:
            out.append(("invalid_dynamic_field", f"Dynamic: {d.strip()!r} is not a field PyPI allows to be dynamic"))
    if md_version != (0, 0):
        present = {k.lower() for k in meta.keys()}
        if "license-expression" in present and md_version < (2, 4):
            out.append(("license_expression_old_metadata",
                        f"License-Expression is set but Metadata-Version is {md_version[0]}.{md_version[1]}; "
                        "twine 6+ and packaging reject it. Rebuild with setuptools>=77 / a PEP 639 backend, "
                        "or move the license to the License field"))
        late = sorted(f for f, since in FIELD_SINCE.items()
                      if f in present and f != "license-expression" and md_version < since)
        if late:
            out.append(("field_newer_than_metadata_version",
                        f"field(s) {late} need a newer Metadata-Version than {md_version[0]}.{md_version[1]}"))
    return out


_URI = re.compile(r"^[A-Za-z][A-Za-z0-9+.-]*:[^\s]+$")


def check_url_fields(meta: email.message.Message) -> List[Pair]:
    out = []
    for field in ("Home-page", "Download-URL"):
        v = (meta.get(field) or "").strip()
        if v and v.upper() != "UNKNOWN" and not _URI.match(v):
            out.append(("bad_url_field", f"{field} {v!r} is not a valid URI (PyPI requires scheme:...)"))
    return out


# --- README rendering hazards ----------------------------------------------

_FENCE = re.compile(r"^\s*(```|~~~)")
# Quantifiers are bounded: an unclosed `[` or `<img` repeated a hundred thousand
# times would otherwise make these quadratic on a hostile long description.
_MD_LINK = re.compile(r"!?\[[^\]]{0,300}\]\(\s{0,20}<?([^)\s>]{1,2000})")
_HTML_SRC = re.compile(r"""<(?:img|a|source)\b[^>]{0,500}?\b(?:src|href)\s{0,20}=\s{0,20}["']([^"']{1,2000})["']""", re.I)
_RST_IMAGE = re.compile(r"^\s*\.\. (?:image|figure)::\s+(\S+)", re.M)
_RST_LINK = re.compile(r"`[^`<\n]{0,300}<([^>\s`<]{1,2000})>`_{1,2}")
_RST_TARGET = re.compile(r"^\s*\.\. _[^:]+:\s+(\S+)", re.M)
_ABSOLUTE = re.compile(r"^(?:[A-Za-z][A-Za-z0-9+.-]*:|//|#|\{|\$)")


def _relative(target: str) -> bool:
    t = target.strip()
    return bool(t) and not _ABSOLUTE.match(t)


def relative_links(text: str, content_type: str) -> List[str]:
    """Relative link/image targets in a long description (PyPI does not resolve them)."""
    found: List[str] = []
    ctype = content_type.lower()
    if "markdown" in ctype or not ctype:
        in_fence = False
        for line in text.splitlines():
            if _FENCE.match(line):
                in_fence = not in_fence
                continue
            if in_fence:
                continue
            line = line[:20000]
            line = re.sub(r"`[^`]{0,300}`", "", line)
            found += [m.group(1) for m in _MD_LINK.finditer(line)]
            found += [m.group(1) for m in _HTML_SRC.finditer(line)]
    if "rst" in ctype or not ctype:
        found += [m.group(1) for m in _RST_IMAGE.finditer(text)]
        found += [m.group(1) for m in _RST_LINK.finditer(text)]
        found += [m.group(1) for m in _RST_TARGET.finditer(text)]
    return [t for t in dict.fromkeys(found) if _relative(t)]


def check_readme(meta: email.message.Message, text: str) -> List[Pair]:
    ctype = (meta.get("Description-Content-Type") or "").split(";")[0]
    rel = relative_links(text[:2_000_000], ctype)
    if not rel:
        return []
    shown = ", ".join(repr(r[:60]) for r in rel[:3])
    return [("readme_relative_links",
             f"long description links to {len(rel)} relative path(s) ({shown}); PyPI does not resolve "
             "them, so they render broken. Use absolute https:// URLs")]


def all_metadata_checks(meta: email.message.Message, md_version: Tuple[int, int]) -> List[Pair]:
    out: List[Pair] = []
    out += check_classifiers(meta)
    out += check_license(meta)
    out += check_requires_python(meta)
    out += check_extras(meta)
    out += check_emails(meta)
    out += check_dynamic_and_versions(meta, md_version)
    out += check_url_fields(meta)
    return out
